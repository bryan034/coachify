import {test,expect} from '@playwright/test';
import {createLocalAccount,fillCurrentEmployment} from './account-helpers';
import {seedCanonicalGoal} from './canonical-career';
test('Career previews validate real sessions, read a document and discard source on reload',async({page})=>{
 const account=await createLocalAccount(page,'Synthetic Career user');
 await page.getByRole('button',{name:'Employed',exact:true}).click();
 await fillCurrentEmployment(page);
 await page.getByRole('button',{name:'No applicable previous education'}).click();
 await page.getByRole('button',{name:'Enter elo',exact:true}).click();
 await expect(page).toHaveURL(/\/getting-started$/);
 await page.getByRole('link', {name:'Go to Home', exact:true}).click();
 await expect(page).toHaveURL(/\/dashboard$/);
 await page.getByRole('navigation').getByRole('link',{name:'Career Goal',exact:true}).click();
 await page.getByRole('tab',{name:'Upload document'}).click();
 const source='Synthetic analyst\nResponsibilities\n• Research & communicate findings.\nSQL or Python.';
 await page.getByLabel('Job description document',{exact:true}).setInputFiles({name:'role.txt',mimeType:'text/plain',buffer:Buffer.from(source)});
 await expect(page.getByRole('textbox',{name:'Review and edit the preview'})).toHaveValue(source);
 await page.getByRole('tab',{name:'Job URL'}).click();await page.getByLabel('Job description URL',{exact:true}).fill('http://127.0.0.1/job');
 await page.getByRole('button',{name:'Import job page'}).click();await expect(page.getByRole('tabpanel').getByRole('alert')).toContainText('Private, local and internal');
 await page.getByRole('tab',{name:'Paste description'}).click();await page.getByRole('textbox',{name:'Job description',exact:true}).fill(source);
 const stored=await page.evaluate(()=>JSON.stringify([Object.entries(localStorage),Object.entries(sessionStorage)]));expect(stored).not.toContain('Synthetic analyst');
 const failure=page.waitForResponse(response=>response.url().includes('/api/v1/career/workspace/operations/')&&response.status()===503);
 const extraction=page.waitForResponse(response=>response.url().endsWith('/api/v1/career/workspace/jd')&&response.request().method()==='POST');
 await page.getByRole('button',{name:'Extract career goal'}).click();
 const response=await extraction;
 expect(response.status()).toBe(202);
 expect(await response.json()).toMatchObject({operation_id:expect.any(String),status:'running'});
 const failedOperation=await failure;
 expect(await failedOperation.json()).toMatchObject({code:'not_configured'});
 await expect(page.getByRole('tabpanel').getByRole('alert')).toContainText('AI is disabled');
 await expect(page).toHaveURL(/\/career-goal$/);
 const input=page.getByRole('textbox',{name:'Job description',exact:true});
 await expect(input).toHaveValue(source);
 await expect(page.getByRole('button',{name:'Retry extraction',exact:true})).toBeEnabled();
 const goals=await account.get('/api/v1/career/goals/current');
 expect(goals.ok()).toBe(true);
 expect((await goals.json()).goal).toBeNull();
 page.once('dialog',dialog=>dialog.accept());
 await page.reload();await expect(page.getByRole('textbox',{name:'Job description',exact:true})).toHaveValue('');
 const signedOut=await page.request.post('/api/v1/career/imports/url',{data:{url:'https://example.test/job'}});expect(signedOut.status()).toBe(401);
});

test('Career goal persists through the real gateway and owner database',async({page})=>{
 const account=await createLocalAccount(page,'Synthetic Goal user');
 await page.getByRole('button',{name:'Employed',exact:true}).click();await fillCurrentEmployment(page);
 await page.getByRole('button',{name:'No applicable previous education'}).click();
 await page.getByRole('button',{name:'Enter elo',exact:true}).click();
 await page.getByRole('navigation').getByRole('link',{name:'Career Goal',exact:true}).click();
 await page.getByRole('button',{name:'Explore careers'}).click();
 await expect(page).toHaveURL(/\/career-goal\/discovery$/);
 await expect(page.getByRole('heading',{name:'Career discovery'})).toBeVisible();
 await seedCanonicalGoal(account,{role:'Synthetic analyst',field:'Research',skills:[]});
 await page.goto('/career-goal/chat');await page.reload();
 await expect(page.getByRole('main')).toContainText('Synthetic analyst');
 const restored=await account.get('/api/v1/career/goals/current');
 expect((await restored.json()).goal.role).toBe('Synthetic analyst');
});
